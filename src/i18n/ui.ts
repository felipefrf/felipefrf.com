export type Lang = 'en' | 'pt';
export const langs: Lang[] = ['en', 'pt'];

/** Prefix a site path with the language. path must start with '/'. */
export const localePath = (lang: Lang, path = '/') => (lang === 'pt' ? `/pt${path === '/' ? '/' : path}` : path);

/** The same page in the other language. */
export const switchPath = (pathname: string, to: Lang) => {
  const bare = pathname.replace(/^\/pt(\/|$)/, '/');
  return localePath(to, bare);
};

